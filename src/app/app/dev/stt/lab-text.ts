export type LabKey = keyof (typeof TEXT)['en'];

export function labText(locale: UiLocale) {
  const dict = locale === 'ru' ? TEXT.ru : locale === 'en' ? TEXT.en : TEXT.uz;
  return (key: LabKey, vars?: Record<string, string | number>) => {
    let s: string = dict[key] ?? TEXT.en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}
